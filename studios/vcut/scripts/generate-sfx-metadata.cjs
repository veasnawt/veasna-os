#!/usr/bin/env node
// One-time (re-run only when packages/vcut/assets/sfx/ changes) precompute step for the bundled SFX
// catalog's zero-copy path (Asset.bundledSfx) — see packages/vcut/src/project/sfxMetadata.generated.ts's
// own header comment for why this needs to exist at all: adding a bundled sound to the timeline used to
// always fetch+re-import a copy of an already-shared file specifically because duration/waveform were
// only ever known AFTER running ffprobe/ffmpeg on it. Precomputing both here, once, for every bundled
// file lets that whole round trip be skipped entirely at "Add" time.
//
// Deliberately plain CommonJS, not TypeScript importing packages/vcut's or studios/vcut's own modules —
// this only needs three things (fs, ffmpeg-static, ffprobe-static), and cross-package TS resolution
// outside Next's own bundler/webpack config is its own can of worms not worth opening for a script this
// small. Run from studios/vcut (`node scripts/generate-sfx-metadata.cjs`) so ffmpeg-static/ffprobe-static
// resolve the exact same way `_lib/ffmpeg.ts`'s own `resolveBinary` does.

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ffmpegBinary = require("ffmpeg-static");
const ffprobeBinary = require("ffprobe-static").path;

const SFX_DIR = path.resolve(__dirname, "../../../packages/vcut/assets/sfx");
const OUTPUT_FILE = path.resolve(__dirname, "../../../packages/vcut/src/project/sfxMetadata.generated.ts");

// Mirrors packages/vcut/src/export/ffmpegCommands.ts's own buildWaveformArgs exactly (WAVEFORM_WIDTH/
// HEIGHT/COLOR included) — see this script's own header comment for why that's duplicated here rather
// than imported.
const WAVEFORM_WIDTH = 1600;
const WAVEFORM_HEIGHT = 100;
const WAVEFORM_COLOR = "0x34d399";

function buildWaveformArgs(input, output) {
  return [
    "-i", input,
    "-f", "lavfi", "-i", `color=c=black@0:s=${WAVEFORM_WIDTH}x${WAVEFORM_HEIGHT}`,
    "-filter_complex",
    `[0:a]aformat=channel_layouts=mono,dynaudnorm=f=150:g=15,` +
      `showwavespic=s=${WAVEFORM_WIDTH}x${WAVEFORM_HEIGHT}:colors=${WAVEFORM_COLOR}[wave];` +
      `[1:v][wave]overlay=format=auto[out]`,
    "-map", "[out]",
    "-frames:v", "1",
    "-y", output,
  ];
}

function probeDuration(filePath) {
  const stdout = execFileSync(ffprobeBinary, ["-v", "quiet", "-print_format", "json", "-show_format", filePath], {
    maxBuffer: 10 * 1024 * 1024,
  }).toString("utf8");
  const data = JSON.parse(stdout);
  const duration = Number(data.format && data.format.duration);
  if (!Number.isFinite(duration) || duration <= 0) throw new Error(`Could not read a duration for ${filePath}`);
  return duration;
}

function main() {
  const files = fs.readdirSync(SFX_DIR).filter((f) => f.toLowerCase().endsWith(".mp3"));
  console.log(`Found ${files.length} bundled SFX files in ${SFX_DIR}`);

  const metadata = {};
  let generated = 0;
  for (const file of files) {
    const input = path.join(SFX_DIR, file);
    const waveformFile = file.replace(/\.mp3$/i, ".png");
    const output = path.join(SFX_DIR, waveformFile);

    const duration = probeDuration(input);
    const sizeBytes = fs.statSync(input).size;
    execFileSync(ffmpegBinary, buildWaveformArgs(input, output), { stdio: ["ignore", "ignore", "pipe"] });
    if (!fs.existsSync(output)) throw new Error(`ffmpeg did not produce a waveform for ${file}`);

    metadata[file] = { duration: Math.round(duration * 1000) / 1000, sizeBytes, waveformFile };
    generated++;
    if (generated % 20 === 0) console.log(`  ...${generated}/${files.length}`);
  }

  const lines = Object.entries(metadata)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([file, m]) =>
        `  ${JSON.stringify(file)}: { duration: ${m.duration}, sizeBytes: ${m.sizeBytes}, waveformFile: ${JSON.stringify(m.waveformFile)} },`
    );

  const content = `/** Auto-generated by studios/vcut/scripts/generate-sfx-metadata.cjs — DO NOT HAND-EDIT.
 *  Regenerate (\`node scripts/generate-sfx-metadata.cjs\` from studios/vcut) after adding, removing, or
 *  replacing any file in packages/vcut/assets/sfx/.
 *
 *  Keyed by \`SfxDefinition.file\` (the bundled filename, e.g. "whoosh-3.mp3") rather than \`.id\` — this
 *  file has no reason to know anything about the curated id/label/category registry in sfx.ts, only
 *  about the raw files sitting in assets/sfx/, so it stays regeneratable from that directory alone.
 *  \`waveformFile\` sits in that SAME directory (assets/sfx/), served by the same sfx/[file]/route.ts
 *  bundled-asset route — a plain sibling PNG, not a separate directory/route of its own.
 *
 *  A filename missing from this map (a brand-new SFX_REGISTRY entry nobody's regenerated this for yet)
 *  is handled gracefully by every consumer, not treated as an error — see SfxPanel.tsx's own fallback
 *  to the ordinary fetch-and-import path for exactly that case. */
export const SFX_METADATA: Record<string, { duration: number; sizeBytes: number; waveformFile: string }> = {
${lines.join("\n")}
};
`;

  fs.writeFileSync(OUTPUT_FILE, content, "utf8");
  console.log(`Wrote ${Object.keys(metadata).length} entries to ${OUTPUT_FILE}`);
}

main();
